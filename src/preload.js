const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('native', {
  pathForFile: (f) => webUtils.getPathForFile(f),
  setLang: (l) => ipcRenderer.send('set-lang', l),
  isTest: !!process.env.CLIPNOVA_TEST_SCRIPT,
  testShot: (file) => ipcRenderer.invoke('test-shot', file),
  testQuit: (code) => ipcRenderer.invoke('test-quit', code),
  pickMedia: (kind) => ipcRenderer.invoke('pick-media', kind),
  fileExists: (p) => ipcRenderer.invoke('file-exists', p),
  saveRecording: (projectId, bytes, ext) => ipcRenderer.invoke('save-recording', projectId, bytes, ext),
  listProjects: () => ipcRenderer.invoke('list-projects'),
  loadProject: (id) => ipcRenderer.invoke('load-project', id),
  saveProject: (p, thumb) => ipcRenderer.invoke('save-project', p, thumb),
  deleteProject: (id) => ipcRenderer.invoke('delete-project', id),
  renameProject: (id, name) => ipcRenderer.invoke('rename-project', id, name),
  pickExportPath: (name) => ipcRenderer.invoke('pick-export-path', name),
  exportStart: (opts) => ipcRenderer.invoke('export-start', opts),
  exportFrame: (frame) => ipcRenderer.invoke('export-frame', frame),
  exportFinish: (cancel) => ipcRenderer.invoke('export-finish', cancel),
  showInFolder: (p) => ipcRenderer.invoke('show-in-folder', p),
  probeMedia: (p) => ipcRenderer.invoke('probe-media', p),
  videoStrip: (p, dur, aspect) => ipcRenderer.invoke('video-strip', p, dur, aspect),
  decodeAudio: (p, rate, ch) => ipcRenderer.invoke('decode-audio', p, rate, ch),
  reverseMedia: (projectId, p, s, e, a) => ipcRenderer.invoke('reverse-media', projectId, p, s, e, a),
  extractFrame: (projectId, p, t) => ipcRenderer.invoke('extract-frame', projectId, p, t),
  decoderOpen: (id, o) => ipcRenderer.invoke('decoder-open', id, o),
  decoderRead: (id) => ipcRenderer.invoke('decoder-read', id),
  decoderClose: (id) => ipcRenderer.invoke('decoder-close', id),
  aiSettingsGet: () => ipcRenderer.invoke('ai-settings-get'),
  aiSettingsSet: (s) => ipcRenderer.invoke('ai-settings-set', s),
  aiListModels: (key) => ipcRenderer.invoke('ai-list-models', key),
  aiTranscribe: (wav, opts) => ipcRenderer.invoke('ai-transcribe', wav, opts),
  aiTranslate: (texts, target) => ipcRenderer.invoke('ai-translate', texts, target),
  aiTts: (projectId, text, voice, style) => ipcRenderer.invoke('ai-tts', projectId, text, voice, style),
  onAiProgress: (fn) => { const h = (e, d) => fn(d); ipcRenderer.on('ai-progress', h); return () => ipcRenderer.removeListener('ai-progress', h); },
  detectSilence: (p, s, e, db, d) => ipcRenderer.invoke('detect-silence', p, s, e, db, d),
  detectScenes: (p, s, e, th) => ipcRenderer.invoke('detect-scenes', p, s, e, th),
  enhanceAudio: (projectId, p, isVideo) => ipcRenderer.invoke('enhance-audio', projectId, p, isVideo),
  saveTextFile: (name, content, ext) => ipcRenderer.invoke('save-text-file', name, content, ext),
  openTextFile: (ext) => ipcRenderer.invoke('open-text-file', ext),
});
